"""Kill tests for the optical-scene contract, without launching Blender."""

from __future__ import annotations

import ast
from pathlib import Path


HERE = Path(__file__).resolve().parent


def main() -> None:
    source = (HERE / "build_scene.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    text = ast.unparse(tree)
    assert "SCENE_SCHEMA" in text
    assert "CYCLES" in text
    assert "observer_distance_m" in text
    assert "focus_offset_m" in text
    assert "external_assets_used" in text
    assert "network_used" in text
    assert "input_injected" in text
    # The experiment must not smuggle an image pair into the scene: focus is
    # generated by geometry and camera DOF, not by an unverified upscaled asset.
    assert "load" not in text or "bpy.data.images.load" not in text
    print("FARMAXIA_085_VIZZ_BLENDER_FOCUS_DISTANCE_KILL_TESTS_VALID")


if __name__ == "__main__":
    main()

